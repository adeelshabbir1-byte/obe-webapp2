# Regenerates lib/migrationProbes.ts from prisma/migration_*.sql. Run: python3 scripts/gen-migration-probes.py
import re, glob, os, json
out = []
for f in sorted(glob.glob('prisma/migration_*.sql')):
    s = open(f).read()
    body = re.sub(r'--[^\n]*', '', s)
    first = next((l.strip('- ').strip() for l in s.splitlines() if l.startswith('--')), '')
    cols = re.findall(r'ALTER TABLE\s+"(\w+)"\s+ADD COLUMN IF NOT EXISTS\s+"(\w+)"', body)
    tabs = re.findall(r'CREATE TABLE IF NOT EXISTS\s+"(\w+)"', body)
    probe = {'t': cols[-1][0], 'c': cols[-1][1]} if cols else ({'t': tabs[-1]} if tabs else None)
    if probe: out.append({'f': os.path.basename(f), 'd': first[:140], **probe})
open('lib/migrationProbes.ts', 'w').write('// Generated by scripts/gen-migration-probes.py from prisma/migration_*.sql: for each file, one table or column it creates, used to tell whether it has been run.\nexport const MIGRATIONS: { f: string; d: string; t: string; c?: string }[] = ' + json.dumps(out, indent=0) + ';\n')
print(len(out))
