import { NextRequest, NextResponse } from "next/server";
import { getAuthenticatedUser } from "../../../lib/session";
import { chairmanIdFor } from "../../../lib/reportScope";
import { examChairman } from "../../../lib/examBranch";
import * as G from "../../../lib/paperGen";
import { PdfDoc } from "../../../lib/pdfDoc";
import { prisma } from "../../../lib/db";
import { withErrors } from "../../../lib/apiHandler";

export const dynamic = "force-dynamic";
const db = prisma as unknown as Record<string, any>;
// Queue item 18. POST { action: propose|pl|omc|return {code, examType, spec?} | policy {examType, policy} | generate {settingId, examDate?}
//   | review {genId, swap?} | error {genId, note} }. GET ?print=<genId> (the Controller, PDF with the trust stamp).
async function who() {
  const user = await getAuthenticatedUser();
  if (!user || !user.mfaVerified) return null;
  const cid = await chairmanIdFor(user as never);
  return { user, cid, controller: (await examChairman(user as never)) === cid };
}
async function GET_handler(req: NextRequest) {
  const w = await who(); if (!w?.controller) return NextResponse.json({ error: "Only the Controller of Examinations prints papers." }, { status: 403 });
  const g = (await db.generatedPaper.findUnique({ where: { id: req.nextUrl.searchParams.get("print") || "" } })) as G.Gen | null;
  if (!g || (g as unknown as { chairmanId: string }).chairmanId !== w.cid) return NextResponse.json({ error: "Not found." }, { status: 404 });
  if (g.status === "GENERATED") return NextResponse.json({ error: "Waiting for its review under the institute's policy." }, { status: 400 });
  const qs = await G.paperItems(w.cid, g);
  const pdf = await PdfDoc.create(`${g.courseCode} ${g.examType} · version ${g.version} · ${g.checkCode}`);
  pdf.title(`${g.courseCode} — ${g.examType} examination`, `Version ${g.version}`);
  qs.forEach((q, i) => { pdf.h2(`Q${i + 1}. (${q.marks} marks · ${q.cloCodes.join(", ")} · ${q.bloom})`); pdf.text(q.text); for (const p of q.parts || []) pdf.text(`${p.label}) ${p.text} [${p.marks}]`); });
  pdf.note(`Generated by OBEHUB from the course question bank under settings approved by the OMC. Version ${g.version}. Check code ${g.checkCode} — verify at ${req.nextUrl.origin}/verify-paper?code=${g.checkCode}`);
  if (g.status !== "PRINTED") {
    await db.generatedPaper.update({ where: { id: g.id }, data: { status: "PRINTED" } });
    const offs = await prisma.course.findMany({ where: { code: g.courseCode, isOffered: true, coordinator: { managedById: w.cid } }, select: { id: true }, take: 1 });
    if (offs[0]) { const Q = await import("../../../lib/qbank"); await Q.recordUse(w.user as never, qs.map((q) => q.id), offs[0].id, g.examType, await Q.currentTerm(offs[0].id), null).catch(() => null); }
  }
  return new NextResponse(Buffer.from(await pdf.save()), { headers: { "Content-Type": "application/pdf", "Content-Disposition": `attachment; filename="${g.courseCode}-${g.examType}-v${g.version}.pdf"` } });
}
async function POST_handler(req: NextRequest) {
  const w = await who(); if (!w) return NextResponse.json({ error: "forbidden" }, { status: 403 });
  const b = (await req.json().catch(() => ({}))) as Record<string, any>;
  const examType = b.examType === "Midterm" ? "Midterm" : "Final";
  try {
    if (["propose", "pl", "omc", "return"].includes(b.action)) { await G.act(w.user as never, w.cid, String(b.code || "").trim().toUpperCase(), examType, b.action, b.spec); return NextResponse.json({ ok: true }); }
    if (b.action === "check") return NextResponse.json(await G.sufficiency(w.cid, String(b.code || "").trim().toUpperCase(), examType, b.spec));
    if (b.action === "policy") { if (!w.controller) return NextResponse.json({ error: "Only the Controller." }, { status: 403 }); await G.setPolicy(w.user as never, w.cid, examType, b.policy === "B" || b.policy === "C" ? b.policy : "A"); return NextResponse.json({ ok: true }); }
    if (b.action === "generate") { if (!w.controller) return NextResponse.json({ error: "Only the Controller generates papers." }, { status: 403 }); return NextResponse.json({ ok: true, ids: await G.generate(w.user as never, w.cid, String(b.settingId), b.examDate ? new Date(String(b.examDate)) : null) }); }
    if (b.action === "review") { await G.review(w.user as never, w.cid, String(b.genId), b.swap === undefined || b.swap === null ? null : Number(b.swap)); return NextResponse.json({ ok: true }); }
    if (b.action === "error") { if (!w.controller) return NextResponse.json({ error: "Only the Controller." }, { status: 403 }); await db.generatedPaper.updateMany({ where: { id: String(b.genId), chairmanId: w.cid }, data: { errorNote: String(b.note || "").slice(0, 1000) } }); return NextResponse.json({ ok: true }); }
  } catch (e) { const m = (e as Error).message || ""; return NextResponse.json({ error: /paperGenSetting|generatedPaper|does not exist/.test(m) ? G.PG_HINT : m }, { status: 400 }); }
  return NextResponse.json({ error: "Unknown action." }, { status: 400 });
}
export const GET = withErrors(GET_handler);
export const POST = withErrors(POST_handler);
