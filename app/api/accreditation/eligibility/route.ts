import { NextRequest, NextResponse } from "next/server";
import ExcelJS from "exceljs";
import { getAuthenticatedUser } from "../../../../lib/session";
import { chairmanIdFor } from "../../../../lib/reportScope";
import { eligibility, saveInputs, ELIGIBILITY_HINT } from "../../../../lib/councilEligibility";
import { sarScope } from "../../../../lib/sarAccess";

const ROLES = ["CHAIRMAN", "DEAN", "HEAD_OF_DEPARTMENT", "PROGRAM_COORDINATOR", "DEPARTMENT_COORDINATOR"];

async function who() {
  const user = await getAuthenticatedUser();
  if (!user || !ROLES.includes(user.role)) return null;
  const chairmanId = await chairmanIdFor(user);
  const scope = await sarScope(user);
  const filter = user.role === "CHAIRMAN" ? {} : user.role === "PROGRAM_COORDINATOR" ? { program: user.leadProgram || "__none" } : { departments: scope.departments.map((d) => d.id) };
  return { user, chairmanId, filter };
}

// GET ?sheet=1[&program=] — the registration / eligibility sheet in Excel.
export async function GET(req: NextRequest) {
  const w = await who();
  if (!w) return NextResponse.json({ error: "forbidden" }, { status: 403 });
  const only = req.nextUrl.searchParams.get("program") || undefined;
  const rows = (await eligibility(w.chairmanId, w.filter)).filter((r) => !only || r.program === only);
  const wb = new ExcelJS.Workbook();
  for (const r of rows) {
    const ws = wb.addWorksheet(`${r.body} ${r.program}`.replace(/[\\/?*[\]:]/g, " ").slice(0, 31));
    ws.columns = [{ width: 34 }, { width: 60 }, { width: 44 }, { width: 12 }, { width: 12 }, { width: 50 }];
    ws.addRow([`${r.body} eligibility — ${r.program}`]).font = { bold: true, size: 14 };
    ws.addRow([`Generated by OBEHUB on ${new Date().toISOString().slice(0, 10)}. ${r.passed} met, ${r.failed} not met, ${r.open} to answer.`]);
    ws.addRow([]);
    ws.addRow(["Program facts"]).font = { bold: true };
    for (const [k, v] of Object.entries(r.facts)) ws.addRow([k, v]);
    ws.addRow([]);
    const h = ws.addRow(["Requirement", "Rule", "Value", "Result", "Source", "Note"]);
    h.font = { bold: true }; h.eachCell((c) => { c.fill = { type: "pattern", pattern: "solid", fgColor: { argb: "FFE8E3D3" } }; });
    for (const c of r.checks) {
      const row = ws.addRow([c.label, c.rule, c.value || "—", c.pass === true ? "Met" : c.pass === false ? "Not met" : "To answer", c.source === "system" ? "System" : c.source === "entered" ? "Entered" : "—", c.note || ""]);
      row.getCell(4).font = { bold: true, color: { argb: c.pass === true ? "FF23894F" : c.pass === false ? "FFC93C3C" : "FFC98A0B" } };
      row.alignment = { wrapText: true, vertical: "top" };
    }
  }
  if (!rows.length) wb.addWorksheet("None").addRow(["No program bound to NBEAC or PEC."]);
  const buf = await wb.xlsx.writeBuffer();
  return new NextResponse(buf as ArrayBuffer, { headers: { "Content-Type": "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet", "Content-Disposition": `attachment; filename="Council-eligibility${only ? `-${only.replace(/[^A-Za-z0-9]+/g, "-")}` : ""}.xlsx"` } });
}

// POST { body, program, key, value } — save one typed-in answer.
export async function POST(req: NextRequest) {
  const w = await who();
  if (!w) return NextResponse.json({ error: "forbidden" }, { status: 403 });
  const b = await req.json().catch(() => ({}));
  const body = String(b.body || ""), program = String(b.program || ""), key = String(b.key || "");
  if (!["NBEAC", "PEC"].includes(body) || !program || !/^[a-zA-Z]{2,20}$/.test(key)) return NextResponse.json({ error: "bad request" }, { status: 400 });
  const mine = await eligibility(w.chairmanId, w.filter);
  if (!mine.some((r) => r.program === program && r.body === body)) return NextResponse.json({ error: "Not your program." }, { status: 403 });
  try { await saveInputs(w.chairmanId, body, program, { [key]: String(b.value ?? "").slice(0, 200) }, w.user.id); }
  catch { return NextResponse.json({ error: ELIGIBILITY_HINT }, { status: 500 }); }
  return NextResponse.json({ ok: true });
}
